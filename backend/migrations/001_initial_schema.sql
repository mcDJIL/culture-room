CREATE TABLE disciplines (
  id text PRIMARY KEY,
  name text NOT NULL UNIQUE,
  note text NOT NULL,
  visual text NOT NULL,
  credit text NOT NULL,
  sort_order integer NOT NULL
);

CREATE TABLE profile (
  id smallint PRIMARY KEY CHECK (id = 1),
  name text NOT NULL,
  headline text NOT NULL,
  location text,
  discipline text
);

CREATE TABLE posts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  author text NOT NULL,
  discipline text NOT NULL,
  location text NOT NULL,
  type text NOT NULL,
  body text NOT NULL,
  image text,
  image_alt text,
  image_credit text,
  tags text[] NOT NULL DEFAULT '{}',
  is_own boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE network_profiles (
  id text PRIMARY KEY,
  name text NOT NULL,
  headline text NOT NULL,
  location text NOT NULL,
  disciplines text[] NOT NULL,
  banner text NOT NULL,
  credit text NOT NULL,
  sort_order integer NOT NULL
);

CREATE TABLE organizations (
  id text PRIMARY KEY,
  name text NOT NULL,
  type text NOT NULL,
  location text NOT NULL,
  description text NOT NULL,
  disciplines text[] NOT NULL,
  accepting boolean NOT NULL,
  banner text NOT NULL,
  credit text NOT NULL,
  sort_order integer NOT NULL
);

CREATE TABLE organization_applications (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id text NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
  reason text NOT NULL CHECK (char_length(reason) BETWEEN 20 AND 2000),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX organization_applications_organization_id_idx ON organization_applications (organization_id);

CREATE TABLE opportunities (
  id text PRIMARY KEY,
  title text NOT NULL,
  detail text NOT NULL,
  sort_order integer NOT NULL
);

CREATE TABLE workshops (
  id text PRIMARY KEY,
  cluster text NOT NULL,
  title text NOT NULL,
  format text NOT NULL,
  description text NOT NULL,
  sort_order integer NOT NULL
);

CREATE TABLE listings (
  id text PRIMARY KEY,
  kind text NOT NULL CHECK (kind IN ('service', 'product')),
  title text NOT NULL,
  discipline text NOT NULL,
  location text NOT NULL,
  description text NOT NULL,
  price integer NOT NULL CHECK (price >= 0),
  unit text NOT NULL,
  stock integer CHECK (stock >= 0),
  image text NOT NULL,
  credit text NOT NULL,
  sort_order integer NOT NULL,
  CHECK ((kind = 'product') = (stock IS NOT NULL))
);

CREATE TABLE slots (
  id text PRIMARY KEY,
  listing_id text NOT NULL REFERENCES listings(id) ON DELETE CASCADE,
  slot_date text NOT NULL,
  slot_time text NOT NULL,
  status text NOT NULL CHECK (status IN ('available', 'booked')),
  sort_order integer NOT NULL
);

CREATE INDEX slots_listing_id_idx ON slots (listing_id);

CREATE TABLE bookings (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  listing_id text NOT NULL REFERENCES listings(id),
  slot_id text NOT NULL UNIQUE REFERENCES slots(id),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE orders (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  listing_id text NOT NULL REFERENCES listings(id),
  quantity integer NOT NULL CHECK (quantity > 0),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE collaborations (
  id text PRIMARY KEY,
  field text NOT NULL,
  title text NOT NULL,
  need text NOT NULL,
  sort_order integer NOT NULL
);

CREATE TABLE drafts (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  kind text NOT NULL CHECK (kind IN ('service', 'collaboration')),
  title text NOT NULL CHECK (char_length(title) BETWEEN 1 AND 160),
  discipline text NOT NULL,
  description text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE viewer_liked_posts (
  item_id integer PRIMARY KEY REFERENCES posts(id) ON DELETE CASCADE
);

CREATE TABLE viewer_saved_posts (
  item_id integer PRIMARY KEY REFERENCES posts(id) ON DELETE CASCADE
);

CREATE TABLE viewer_connections (
  item_id text PRIMARY KEY REFERENCES network_profiles(id) ON DELETE CASCADE
);

CREATE TABLE viewer_followed_organizations (
  item_id text PRIMARY KEY REFERENCES organizations(id) ON DELETE CASCADE
);

CREATE TABLE viewer_followed_disciplines (
  item_id text PRIMARY KEY REFERENCES disciplines(id) ON DELETE CASCADE
);

CREATE TABLE viewer_joined_collaborations (
  item_id text PRIMARY KEY REFERENCES collaborations(id) ON DELETE CASCADE
);
